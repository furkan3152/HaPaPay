import { readFile, writeFile } from "node:fs/promises";
import solc from "solc";
import { keccak256, stringToHex, type Abi } from "viem";

/**
 * Compiles the Elysium contracts (contracts/elysium) and writes `src/domain/elysium-artifacts.ts`: the ABI and the
 * creation bytecode the admin console deploys from the admin's own wallet, and the runtime code with its immutable
 * ranges, so the server accepts a registered address only when its code is exactly one of these contracts.
 *
 *   npm run generate:elysium
 */
export const ELYSIUM_CONTRACT_SOURCES = {
  ElysaPayRouter: "contracts/elysium/ElysaPayRouter.sol",
  ElysaToken: "contracts/elysium/ElysaToken.sol",
  ElysaPass: "contracts/elysium/ElysaPass.sol",
} as const;
export type ElysiumContractName = keyof typeof ELYSIUM_CONTRACT_SOURCES;

type Output = {
  errors?: Array<{ severity: string; formattedMessage: string }>;
  contracts: Record<string, Record<string, {
    abi: Abi;
    evm: {
      bytecode: { object: string };
      deployedBytecode: { object: string; immutableReferences?: Record<string, Array<{ start: number; length: number }>> };
    };
  }>>;
};

export async function compileElysiumContract(name: ElysiumContractName) {
  const path = ELYSIUM_CONTRACT_SOURCES[name];
  const source = await readFile(new URL(`../${path}`, import.meta.url), "utf8");
  const input = {
    language: "Solidity",
    sources: { [path]: { content: source } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      // Elysium runs stock ArbOS (Arbitrum Nitro): Cancun opcodes are available.
      evmVersion: "cancun",
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "evm.deployedBytecode.immutableReferences"] } },
    },
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input))) as Output;
  const diagnostics = (output.errors ?? []).filter((entry) => entry.severity === "error" || entry.severity === "warning");
  if (diagnostics.length) throw new Error(diagnostics.map((entry) => entry.formattedMessage).join("\n"));
  const contract = output.contracts[path][name];
  const immutables = Object.values(contract.evm.deployedBytecode.immutableReferences ?? {}).flat()
    .map(({ start, length }) => [start, length] as [number, number]).sort((a, b) => a[0] - b[0]);
  return {
    contractName: name,
    compiler: solc.version(),
    sourceHash: keccak256(stringToHex(source)),
    abi: contract.abi,
    bytecode: `0x${contract.evm.bytecode.object}`,
    runtime: `0x${contract.evm.deployedBytecode.object}`,
    immutables,
  };
}

async function main() {
  const names = Object.keys(ELYSIUM_CONTRACT_SOURCES) as ElysiumContractName[];
  const compiled = await Promise.all(names.map(compileElysiumContract));
  const body = compiled.map((artifact) => `export const ${artifact.contractName.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()}_ARTIFACT = ${JSON.stringify(artifact, null, 2)} as const;`).join("\n\n");
  const file = `// Generated by \`npm run generate:elysium\` from contracts/elysium. Do not edit by hand.
// The admin console deploys this creation bytecode from the admin's own wallet; the server registers an address only
// when its runtime code equals \`runtime\` outside the immutable ranges.
/* eslint-disable */

${body}
`;
  await writeFile(new URL("../src/domain/elysium-artifacts.ts", import.meta.url), file);
  console.log(compiled.map((artifact) => `${artifact.contractName}: ${(artifact.bytecode.length - 2) / 2} bytes`).join("\n"));
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop()!)) await main();
