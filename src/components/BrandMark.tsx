/** The bird fills 50 of the tile's 64 units. */
const unit = (value: number) => +(7 + value * (50 / 24)).toFixed(2);
/** The shoulder, where the wing meets the body: the dots gather from here outward. */
const SHOULDER = [14.6, 9.4];
const farthest = Math.max(...[...WING, ...BODY].map(([x, y]) => Math.hypot(x - SHOULDER[0], y - SHOULDER[1])));
const dot = ([x, y, r]: Dot, index: number) => {
  // Before it assembles, each dot waits a little way out from the shoulder, along the line from it; the dots nearest
  // the shoulder arrive first.
  const distance = Math.hypot(x - SHOULDER[0], y - SHOULDER[1]);
  const angle = Math.atan2(y - SHOULDER[1], x - SHOULDER[0]) + (index % 2 ? 0.5 : -0.5);
  const reach = 6 + (index % 5) * 1.6;
  const style = { "--i": +(distance / farthest).toFixed(3), "--sx": `${(Math.cos(angle) * reach).toFixed(1)}px`, "--sy": `${(Math.sin(angle) * reach).toFixed(1)}px` } as CSSProperties;
  return <circle key={index} className="mark-dot" cx={unit(x)} cy={unit(y)} r={+(r * (50 / 24)).toFixed(2)} style={style} />;
};
const wing = WING.map((point, index) => dot(point, index));
const body = BODY.map((point, index) => dot(point, WING.length + index));

/**
 * The HaPaPay mark: the dotted bird on a tile. In the header its dots gather into the bird when the page opens, and
 * hovering the brand makes the wing flap: the wing folds across the line where it meets the body (at -42 degrees) at the
 * shoulder (14.6, 9.4 in the bird's box, 37.42, 26.58 on the tile), which is where `.mark-wing` turns in the style
 * sheet. The small birds that report a sent request, a pending draft and the vault route are this mark without its
 * tile. It is decorative everywhere it appears, so it is hidden from assistive technology.
 */
export function BrandMark({ className = "", tile = false }: { className?: string; tile?: boolean }) {
  return <svg className={`brand-mark ${tile ? "brand-mark-tile" : ""} ${className}`} viewBox="0 0 64 64" aria-hidden="true" focusable="false">
    {tile && <rect className="mark-tile" x="0.5" y="0.5" width="63" height="63" rx="15.5" />}
    <g className="mark-wing">{wing}</g>
    {body}
  </svg>;
}
